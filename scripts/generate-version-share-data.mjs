#!/usr/bin/env node

import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname } from 'node:path';

const SOURCE_URL = 'https://raw.githubusercontent.com/Fyrd/caniuse/main/data.json';

const outputTsPath = new URL('../src/generated-version-share.ts', import.meta.url).pathname;
const outputJavaPath = new URL(
  '../android/src/main/java/app/capgo/webviewversionchecker/GeneratedVersionShareData.java',
  import.meta.url,
).pathname;

const timeoutMs = 15000;

const parseMajorVersion = (input) => {
  if (input === null || input === undefined) {
    return null;
  }

  const value = String(input).trim();
  if (!value) {
    return null;
  }

  const normalized = value.startsWith('v') || value.startsWith('V') ? value.slice(1) : value;
  const match = normalized.match(/(\d+)/);
  if (!match) {
    return null;
  }

  const major = Number.parseInt(match[1], 10);
  return Number.isFinite(major) && major >= 0 ? major : null;
};

const normalizePercent = (input) => {
  const value = typeof input === 'number' ? input : Number(input);
  if (!Number.isFinite(value)) {
    return null;
  }
  const clamped = Math.min(100, Math.max(0, value));
  return Number(clamped.toFixed(6));
};

const mergeUsageGlobal = (target, usageGlobal, { override = false } = {}) => {
  if (!usageGlobal || typeof usageGlobal !== 'object') {
    return;
  }

  for (const [versionKey, shareRaw] of Object.entries(usageGlobal)) {
    const major = parseMajorVersion(versionKey);
    const share = normalizePercent(shareRaw);
    if (major === null || share === null || share <= 0) {
      continue;
    }
    if (!override && target.has(major)) {
      continue;
    }
    target.set(major, share);
  }
};

const extractShareMap = (rawData) => {
  const agents = rawData?.agents ?? {};
  const map = new Map();

  // Prefer Android-specific buckets.
  mergeUsageGlobal(map, agents?.and_chr?.usage_global, { override: false });
  mergeUsageGlobal(map, agents?.android?.usage_global, { override: false });

  // If Android buckets are sparse, fill missing majors from Chrome global.
  if (map.size < 5) {
    mergeUsageGlobal(map, agents?.chrome?.usage_global, { override: false });
  }

  return Object.fromEntries([...map.entries()].sort((a, b) => b[0] - a[0]).map(([major, share]) => [String(major), share]));
};

const generateTs = (shareMap, generatedAtIso) => {
  const prettyJson = JSON.stringify(shareMap, null, 2);
  return `/* eslint-disable */
/**
 * AUTO-GENERATED FILE. DO NOT EDIT.
 * Generated by: scripts/generate-version-share-data.mjs
 * Source: ${SOURCE_URL}
 * Generated at: ${generatedAtIso}
 */

export const DEFAULT_VERSION_SHARE_DATA_SOURCE = 'generatedVersionShareByMajor';
export const DEFAULT_VERSION_SHARE_GENERATED_AT = '${generatedAtIso}';
export const DEFAULT_VERSION_SHARE_BY_MAJOR: Record<string, number> = ${prettyJson};
`;
};

const escapeJavaString = (value) => value.replace(/\\/g, '\\\\').replace(/"/g, '\\"');

const generateJava = (shareMap, generatedAtIso) => {
  const compactJson = JSON.stringify(shareMap);
  const escaped = escapeJavaString(compactJson);
  return `package app.capgo.webviewversionchecker;

import org.json.JSONObject;

final class GeneratedVersionShareData {

    private static final String GENERATED_AT = "${generatedAtIso}";
    private static final String DATA_SOURCE = "generatedVersionShareByMajor";
    private static final String JSON_DATA = "${escaped}";

    private GeneratedVersionShareData() {}

    static JSONObject getDefaultVersionShareByMajor() {
        try {
            return new JSONObject(JSON_DATA);
        } catch (Exception ignored) {
            return new JSONObject();
        }
    }

    static String getDataSource() {
        return DATA_SOURCE;
    }

    static String getGeneratedAt() {
        return GENERATED_AT;
    }
}
`;
};

const ensureParentDir = async (filePath) => {
  await mkdir(dirname(filePath), { recursive: true });
};

const hasExistingGeneratedFiles = async () => {
  try {
    await Promise.all([readFile(outputTsPath, 'utf8'), readFile(outputJavaPath, 'utf8')]);
    return true;
  } catch {
    return false;
  }
};

const fetchWithTimeout = async (url, timeout) => {
  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), timeout);

  try {
    const response = await fetch(url, {
      signal: controller.signal,
      headers: {
        Accept: 'application/json',
      },
    });
    if (!response.ok) {
      throw new Error(`HTTP ${response.status}`);
    }
    return await response.json();
  } finally {
    clearTimeout(timer);
  }
};

const writeOutputs = async (shareMap) => {
  const generatedAtIso = new Date().toISOString();
  const tsContent = generateTs(shareMap, generatedAtIso);
  const javaContent = generateJava(shareMap, generatedAtIso);

  await ensureParentDir(outputTsPath);
  await ensureParentDir(outputJavaPath);
  await Promise.all([writeFile(outputTsPath, tsContent, 'utf8'), writeFile(outputJavaPath, javaContent, 'utf8')]);
};

const main = async () => {
  try {
    const data = await fetchWithTimeout(SOURCE_URL, timeoutMs);
    const shareMap = extractShareMap(data);

    if (Object.keys(shareMap).length === 0) {
      throw new Error('No usable version-share entries extracted from source data.');
    }

    await writeOutputs(shareMap);
    console.log(`Generated version-share defaults with ${Object.keys(shareMap).length} majors.`);
    return;
  } catch (error) {
    const fallbackAvailable = await hasExistingGeneratedFiles();
    if (fallbackAvailable) {
      console.warn(`Warning: Could not refresh version-share data (${String(error)}). Keeping existing generated files.`);
      return;
    }
    throw error;
  }
};

await main();
